# Basic Variables and Data Types in Python

print("=== VARIABLES AND DATA TYPES ===")
print()

# String variables
name = "Alice"
greeting = "Hello, World!"
print(f"String: {name}")
print(f"String: {greeting}")
print()

# Numbers
age = 25
height = 5.8
temperature = -10
print(f"Integer: {age}")
print(f"Float: {height}")
print(f"Negative number: {temperature}")
print()

# Boolean
is_student = True
is_working = False
print(f"Boolean True: {is_student}")
print(f"Boolean False: {is_working}")
print()

# Basic operations
sum_result = 10 + 5
difference = 20 - 8
product = 6 * 7
division = 15 / 3
print(f"Addition: 10 + 5 = {sum_result}")
print(f"Subtraction: 20 - 8 = {difference}")
print(f"Multiplication: 6 * 7 = {product}")
print(f"Division: 15 / 3 = {division}")
print()

# String operations
first_name = "John"
last_name = "Doe"
full_name = first_name + " " + last_name
print(f"String concatenation: {full_name}")
print(f"String length: {len(full_name)}")
print(f"Uppercase: {full_name.upper()}")
print(f"Lowercase: {full_name.lower()}")
